-- Preparacion de Snowflake para el pipeline (se corre UNA sola vez, en un Worksheet).
-- Seleccionar todo (Ctrl + A) y ejecutar (Ctrl + Enter).
USE ROLE ACCOUNTADMIN;

-- 1. Motor de consultas, base de datos y capas
CREATE WAREHOUSE IF NOT EXISTS PSET2_WH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS CARTERA;
CREATE SCHEMA IF NOT EXISTS CARTERA.RAW;
CREATE SCHEMA IF NOT EXISTS CARTERA.BRONZE;
CREATE SCHEMA IF NOT EXISTS CARTERA.SILVER;
CREATE SCHEMA IF NOT EXISTS CARTERA.GOLD;
CREATE SCHEMA IF NOT EXISTS CARTERA.SEGURIDAD;

-- 2. Rol del pipeline, con permisos sobre las capas
CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT USAGE ON DATABASE CARTERA TO ROLE PSET2_ROLE;
GRANT ALL ON SCHEMA CARTERA.RAW TO ROLE PSET2_ROLE;
GRANT ALL ON SCHEMA CARTERA.BRONZE TO ROLE PSET2_ROLE;
GRANT ALL ON SCHEMA CARTERA.SILVER TO ROLE PSET2_ROLE;
GRANT ALL ON SCHEMA CARTERA.GOLD TO ROLE PSET2_ROLE;

-- 3. Usuario de servicio: el que usan Kestra, dbt y Spark (no es una persona)
CREATE USER IF NOT EXISTS PSET2_SERVICE
  TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE
  DEFAULT_WAREHOUSE = PSET2_WH;
GRANT ROLE PSET2_ROLE TO USER PSET2_SERVICE;

-- 4. Snowflake ya no acepta contrasenas para programas: se usa un token (PAT).
--    Esta politica permite usar el token sin configurar una politica de red.
CREATE AUTHENTICATION POLICY IF NOT EXISTS CARTERA.SEGURIDAD.POLITICA_PAT
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);
ALTER USER PSET2_SERVICE SET AUTHENTICATION POLICY CARTERA.SEGURIDAD.POLITICA_PAT;

-- 5. Token del pipeline (valido 30 dias).
--    Copia el valor de token_secret: se muestra UNA sola vez.
ALTER USER PSET2_SERVICE ADD PROGRAMMATIC ACCESS TOKEN PSET2_TOKEN
  ROLE_RESTRICTION = 'PSET2_ROLE'
  DAYS_TO_EXPIRY = 30;