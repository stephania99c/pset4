select
    nullif(trim(id_operacion), '')                          as id_operacion,
    nullif(trim(numero_operacion), '')                      as numero_operacion,
    upper(nullif(trim(tipo_pagare), ''))                    as tipo_pagare,
    nullif(trim(identificacion), '')                        as cliente_id,
    try_to_date(fecha_corte)                                as fecha_corte,
    upper(nullif(trim(estado_operacion), ''))               as estado_operacion,
    try_to_number(dias_mora)                                as dias_mora,
    nullif(trim(rango_mora), '')                            as rango_mora,
    try_to_number(cuotas_por_pagar)                         as cuotas_por_pagar,
    try_to_number(total_cuotas)                             as total_cuotas,
    try_to_number(cuotas_pagadas)                           as cuotas_pagadas,
    try_to_number(cuotas_mora)                              as cuotas_mora,
    try_to_decimal(dia_pago, 5, 1)::integer                 as dia_pago,
    try_to_decimal(capital_insoluto, 18, 2)                 as capital_insoluto,
    try_to_decimal(saldo_cuota_mas_vencida, 18, 2)          as saldo_cuota_mas_vencida,
    try_to_decimal(valor_deuda_exigible, 18, 2)             as valor_deuda_exigible,
    try_to_decimal(valor_cuota_exigible_vigente, 18, 2)     as valor_cuota_exigible_vigente,
    try_to_decimal(capital_vencido, 18, 2)                  as capital_vencido,
    try_to_date(fecha_primera_cuota)                        as fecha_primera_cuota,
    try_to_date(fecha_proxima_cuota)                        as fecha_proxima_cuota,
    try_to_decimal(monto_financiado, 18, 2)                 as monto_financiado,
    try_to_decimal(tasa_nominal, 10, 4)                     as tasa_nominal,
    try_to_date(fecha_efectiva)                             as fecha_efectiva,
    upper(nullif(trim(tipo_garantia), ''))                  as tipo_garantia,
    try_to_date(fecha_primera_cuota_mora)                   as fecha_primera_cuota_mora,
    try_to_timestamp(_fecha_carga)                          as fecha_carga
from {{ source('raw', 'cartera_diaria') }}